"""Render audit/raw/verification.json as audit/CONTENT-VERIFICATION.md."""
import html
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
r = json.loads((ROOT / 'audit/raw/verification.json').read_text(encoding='utf-8'))


def clean(s):
    s = re.sub(r'<sup>(.*?)</sup>', r'^\1', str(s or ''))
    s = html.unescape(re.sub(r'</?[a-zA-Z][^<>]*>', '', s))
    return s.replace('|', '\\|').replace('\n', ' ').strip()


_SRC = {}


def source_line(f, kind, group, idx):
    """Line number of the item in the page source. Items are written one per line,
    so count item lines from the start of the group (BANKS) or of `const T=[`."""
    if f not in _SRC:
        _SRC[f] = (ROOT / f).read_text(encoding='utf-8').split('\n')
    lines = _SRC[f]
    start = None
    for n, l in enumerate(lines):
        if kind == 'bank' and re.match(r"\s*'" + re.escape(group) + r"'\s*:\s*\[", l):
            start = n
            break
        if kind == 'test' and l.startswith('const T=['):
            start = n
            break
    if start is None:
        return None
    seen = -1
    for n in range(start + 1, len(lines)):
        if lines[n].lstrip().startswith('{'):
            seen += 1
            if seen == int(idx):
                return n + 1
    return None


def loc(i):
    f, kind, group, idx = i['id'].split(':')
    where = f'`BANKS[\'{group}\'][{idx}]`' if kind == 'bank' else f'`T[{idx}]`'
    ln = source_line(f, kind, group, idx)
    link = f'[{f}:{ln}](../{f}#L{ln})' if ln else f
    return f'{link} {where} ({"practice" if kind == "bank" else "practice test"}, topic {i["topic"]})'


def show(v):
    v = str(v)
    v = re.sub(r'Interval\.open\((.+?), oo\)', r'x > \1', v)
    v = re.sub(r'Interval\((.+?), oo\)', r'x ≥ \1', v)
    return v.replace('Reals', 'all real numbers').replace('NO SOLUTION', 'no solution')


out = []
w = out.append
w('# Content verification\n')
w('Generated by `python tools/verify/report.py` from `audit/raw/verification.json`.')
w('Reproduce from scratch with:\n')
w('```bash\nnode tools/extract-items.mjs && python tools/verify/verify_items.py && python tools/verify/report.py\n```\n')
w('## Method\n')
w('- **Source of items.** `tools/extract-items.mjs` loads each unit page in headless Chrome and reads the `BANKS`, `T` '
  'and `VQB` arrays exactly as the browser sees them (`audit/raw/items.json`). There are **no problem generators** '
  'in the site: every practice and test item is a static object, so "every static item once" covers the whole bank. '
  'The 10,000-draw requirement is applied to *set assembly* instead (below).')
w('- **Independent answers.** `tools/verify/handlers.py` re-solves each item from its own text with SymPy '
  '(exact rationals, `solveset`, `linsolve`, `reduce_inequalities`, polynomial arithmetic). It parses the raw strings '
  'itself and never calls or imports site code (`isMatch`, `formatEq` and the rest are not used).')
w('- **Items no parser covers** (word problems, definitions, pictures) have hand-written independent solutions in '
  '`tools/verify/manual.py`: an equation SymPy solves, a definition, or a reading of the drawn SVG recovered in maths '
  'coordinates by `tools/verify/svgread.py` (contact sheets in `audit/raw/svgs/`).')
w('- **Comparison.** The site key is parsed separately into the same type (number, solution set, interval, point, '
  'expression) and compared for mathematical equality, so `x = 5` vs `5` or `2x+3` vs `3+2x` are not counted as '
  'mismatches. A key that does not parse at all is a mismatch.')
w('- **Also checked:** duplicate items within a bank or test pool; 10,000 seeded draws (seed 219) of every 5-problem '
  'practice set and every assembled practice test, mirroring the site\'s slice logic; special-case type vs topic label '
  '(5.4/6.4 must be no-solution/all-reals, 5.1–5.3/6.2–6.3 must not); malformed `<sup>` markup; scratch work left in '
  'keys or explanations; explanations that contradict the key; vocabulary quiz answer indices and duplicate options.\n')

tot = Counter()
for c in r['units'].values():
    tot.update(c)
w('## Counts per unit\n')
w('| Unit page | Items checked | Match | **Mismatch** | Ambiguous | Flagged (markup / hint) | Unverified |')
w('|---|---:|---:|---:|---:|---:|---:|')
for f, c in r['units'].items():
    w(f'| {f} | {c.get("checked", 0)} | {c.get("match", 0)} | **{c.get("mismatch", 0)}** | {c.get("ambiguous", 0)} | '
      f'{c.get("flagged", 0)} | {c.get("unverified", 0)} |')
w(f'| **Total** | **{tot["checked"]}** | {tot["match"]} | **{tot["mismatch"]}** | {tot["ambiguous"]} | {tot["flagged"]} | '
  f'{tot.get("unverified", 0)} |\n')
w(f'{tot["checked"]} free-response items = practice banks + practice-test pools across 13 unit pages. '
  f'Vocabulary quiz items ({sum(len(u.get("vqb") or []) for u in json.loads((ROOT / "audit/raw/items.json").read_text(encoding="utf-8")).values())}) '
  'are multiple choice and are checked separately below.\n')

w('## Every failing item\n')
w('Each row: where it lives, the problem, the site\'s key, the independently computed answer, and how it was computed.\n')
w('| # | Location | Problem | Site key | Independent answer | Method / note |')
w('|---|---|---|---|---|---|')
n = 0
for i in r['items']:
    if i['status'] != 'mismatch':
        continue
    n += 1
    note = '; '.join(clean(f) for f in i['flags'] if not f.startswith('HINT-VS')) or ''
    w(f'| {n} | {loc(i)} | {clean(i["q"])} {clean(i["eq"])} | `{clean(i["key"])}` | **{clean(show(i["independent"]))}** | '
      f'{clean(i["method"])}{"; " + note if note else ""} |')
w('')

w('### What the explanation (hint) says for each failing item\n')
w('The hint is shown to students after a wrong answer. In most failing items the hint already contains the correct '
  'working and contradicts the key, which points to the key having been typed wrong rather than the maths being '
  'misunderstood.\n')
w('| Location | Hint text shown to students |')
w('|---|---|')
for i in r['items']:
    if i['status'] == 'mismatch':
        w(f'| {loc(i)} | {clean(i["hint"])} |')
w('')

w('## Ambiguous items (content decisions for the teacher)\n')
w('| Location | Problem | Site key | Why it is ambiguous |')
w('|---|---|---|---|')
for i in r['items']:
    for f in i['flags']:
        if f.startswith('AMBIGUOUS'):
            w(f'| {loc(i)} | {clean(i["q"])} {clean(i["eq"])} | `{clean(i["key"])}` | {clean(f[11:])} |')
w('')

w('## Other flags (key is correct, but what students see is wrong or unprofessional)\n')
w('| Location | Flag | Text |')
w('|---|---|---|')
for i in r['items']:
    for f in i['flags']:
        if f.startswith(('MARKUP', 'HINT-WORKING', 'HINT:', 'LABEL')) and i['status'] != 'mismatch':
            w(f'| {loc(i)} | {f.split(":")[0]} | {clean(f.split(":", 1)[1])} {"— " + clean(i["hint"])[:160] if f.startswith("HINT-WORKING") else ""} |')
w('')
w('`MARKUP` items render wrongly: for example `5x<sup>2(x</sup> - 3)` displays the opening parenthesis and the `x` '
  'inside the exponent, so the student sees 5x raised to "2(x", minus 3, instead of 5x²(x − 3). '
  'The verifier repairs the markup to compute the intended answer; the key matches the intended problem.\n')

w('## Duplicates and set assembly (10,000 seeded draws per unit)\n')
w('| Unit page | Practice sets drawn | Sets with a repeated problem | Tests drawn | Tests with a repeated problem | Test length |')
w('|---|---:|---:|---:|---:|---|')
for f, d in r['draws'].items():
    w(f'| {f} | {d["practice_sets_drawn"]} | {d["practice_sets_with_duplicate"]} | {d["tests_drawn"]} | '
      f'{d["tests_with_duplicate"]} | {", ".join(k + " questions" for k in d["test_length"])} |')
w('')
if r['duplicates']:
    w('Exact repeats found between pools:\n')
    for d in r['duplicates']:
        w(f'- {d["unit"]} — {d["kind"]}: test index {d["idx"]} {clean(d["q"])}')
    w('')

w('## Vocabulary quiz checks\n')
for v in r.get('vocab', []):
    w(f'- **{v["unit"]}**' + (f' `VQB[{v["idx"]}]`' if v['idx'] is not None else '') + f' — {clean(v["issue"])}'
      + (f' — "{clean(v["q"])}" options {v.get("opts")}' if v.get('opts') else ''))
w('')

w('## Limits of this verification\n')
w('- Picture items were checked by recovering coordinates from the SVG source, plus a visual pass over the rendered '
  'contact sheets. Parabolas are drawn as straight-segment polylines, and several y-axes have unevenly spaced labels; '
  'only differences that change the answer are counted as mismatches.')
w('- "Correct" for words-based items (definitions, yes/no) is judged against standard Algebra 1 usage; where usage '
  'varies the item is listed as ambiguous rather than wrong.')
w('- Whether a student\'s *typed* answer is accepted is a separate question, covered by the checker corpus '
  '(`tests/checker-corpus.json`).')

(ROOT / 'audit/CONTENT-VERIFICATION.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote audit/CONTENT-VERIFICATION.md;', n, 'failing items')
